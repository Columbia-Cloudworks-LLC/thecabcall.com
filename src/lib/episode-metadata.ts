const AI_DISCLAIMER_REGEX =
  /(?:\r?\n|\s)*\*?Disclaimer:\s*The media and artwork for this episode were generated by AI using Google Gemini\.?\*?/gi;

export const CANONICAL_PODCAST_AI_COLOPHON =
  "Audio synthesis, conversational voices, and episode artwork across The CAB Call Podcast are generated with AI assistance (Google NotebookLM & Google Gemini) from human-curated Trestleboard dispatches and research dossiers.";

/**
 * Strips inline or trailing AI disclaimer strings from descriptions or transcripts.
 */
export function stripAiDisclaimers(text: string): string {
  if (!text) return "";
  return text.replace(AI_DISCLAIMER_REGEX, "").trim();
}

function cleanMarkdownInline(text: string): string {
  return text
    .replace(/\[cite_start\]/gi, "")
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, "$1")
    .replace(/\(([^)]+)\)\[(https?:\/\/[^\]\s]+)\]/g, "$1")
    .replace(/\[([^\]]+)\]\[(https?:\/\/[^\]\s]+)\]/g, "$1")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*\n]+)\*/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\\_/g, "_")
    .replace(/\s{2,}/g, " ")
    .trim();
}

/**
 * Extracts structured external sources (NotebookLM links, Source #N entries, and Markdown classification tables)
 * from raw episode metadata/description text.
 */
export function extractExternalSourcesFromText(
  rawText: string,
  episodeTitle?: string
): EpisodeExternalSource[] {
  if (!rawText) return [];
  const sources: EpisodeExternalSource[] = [];
  const seenKeys = new Set<string>();

  const addSource = (source: EpisodeExternalSource) => {
    const cleanTitle = source.title.replace(/^\*+|\*+$/g, "").trim();
    if (!cleanTitle) return;
    const key = `${cleanTitle.toLowerCase()}::${(source.url || "").toLowerCase()}`;
    if (seenKeys.has(key)) return;
    seenKeys.add(key);
    sources.push({
      ...source,
      title: cleanTitle,
    });
  };

  const lines = rawText.replace(/\r\n/g, "\n").split("\n");

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    // Check for standalone NotebookLM URL or "Sources: https://..."
    const notebookMatch = line.match(/(https?:\/\/notebooklm\.google\.com\/\S+)/i);
    if (notebookMatch && !/Source\s*#\d+\s*:/i.test(line)) {
      const url = notebookMatch[1].replace(/[.,;)]+$/, "").trim();
      addSource({
        title: episodeTitle
          ? `${episodeTitle} — Google NotebookLM Research Dossier`
          : "Google NotebookLM Research Dossier",
        url,
        sourceType: "NotebookLM Research Dossier",
      });
      continue;
    }

    // Check for Source #N patterns (either on their own line or inline after "Primary Sources Referenced:")
    if (/Source\s*#\d+\s*:/i.test(line)) {
      // Split if multiple Source #N appear on one line
      const segments = line.split(/(?=(?:[-*]\s*)?\*{0,2}Source\s*#\d+\*{0,2}\s*:)/i);
      for (const seg of segments) {
        const matchHeader = seg.match(/Source\s*#\d+\*{0,2}\s*:\*{0,2}\s*(.+)$/i);
        if (!matchHeader) continue;
        const payload = matchHeader[1].trim();

        // Pattern 1: [Title]\s*(https://...)
        const stdMd = payload.match(/\[([^\]]+)\]\s*\((https?:\/\/[^)\s]+)\)/);
        if (stdMd) {
          addSource({
            title: stdMd[1].trim(),
            url: stdMd[2].trim(),
            sourceType: stdMd[2].includes("notebooklm.google.com")
              ? "NotebookLM Research Dossier"
              : "Primary Reference",
          });
          continue;
        }

        // Pattern 2: (Title)\s*[https://...]
        const revMd = payload.match(/\(([^)]+)\)\s*\[(https?:\/\/[^\]\s]+)\]/);
        if (revMd) {
          addSource({
            title: revMd[1].trim(),
            url: revMd[2].trim(),
            sourceType: revMd[2].includes("notebooklm.google.com")
              ? "NotebookLM Research Dossier"
              : "Primary Reference",
          });
          continue;
        }

        // Pattern 3: [Title]\s*[https://...]
        const dblBracket = payload.match(/\[([^\]]+)\]\s*\[(https?:\/\/[^\]\s]+)\]/);
        if (dblBracket) {
          addSource({
            title: dblBracket[1].trim(),
            url: dblBracket[2].trim(),
            sourceType: dblBracket[2].includes("notebooklm.google.com")
              ? "NotebookLM Research Dossier"
              : "Primary Reference",
          });
          continue;
        }

        // Pattern 4: bare URL (e.g. Source #1: https://notebooklm.google.com/...)
        const bareUrl = payload.match(/(https?:\/\/\S+)/);
        if (bareUrl) {
          const url = bareUrl[1].replace(/[.,;)]+$/, "").trim();
          const nonUrlTitle = payload.replace(bareUrl[1], "").replace(/^[-–—:\s(\[]+|[-–—:\s)\]]+$/g, "").trim();
          const fallbackTitle = episodeTitle
            ? `${episodeTitle} — Research Notebook`
            : "NotebookLM Primary Research Dossier";
          addSource({
            title: nonUrlTitle || fallbackTitle,
            url,
            sourceType: url.includes("notebooklm.google.com")
              ? "NotebookLM Research Dossier"
              : "Primary Reference",
          });
          continue;
        }
      }
    }

    // Check for Markdown table rows: | Source Title | Publication Date | Author / Credentials | Source Type |
    if (line.startsWith("|") && line.endsWith("|")) {
      const cells = line
        .slice(1, -1)
        .split("|")
        .map((c) => c.trim());
      if (cells.length >= 2) {
        // Skip separator row | :--- | :--- |
        if (cells.every((c) => /^:?-{2,}:?$/.test(c))) {
          continue;
        }
        // Skip header row
        if (
          /^source\s+title$/i.test(cells[0].replace(/\*+/g, "").trim()) ||
          /^title$/i.test(cells[0].replace(/\*+/g, "").trim())
        ) {
          continue;
        }
        const titleCell = cleanMarkdownInline(cells[0]);
        const pubDateCell = cells[1] ? cleanMarkdownInline(cells[1]) : undefined;
        const authorCell = cells[2] ? cleanMarkdownInline(cells[2]) : undefined;
        const sourceTypeCell = cells[3] ? cleanMarkdownInline(cells[3]) : undefined;
        if (titleCell) {
          addSource({
            title: titleCell,
            publicationDate: pubDateCell || undefined,
            author: authorCell || undefined,
            sourceType: sourceTypeCell || undefined,
          });
        }
      }
    }
  }

  return sources;
}

/**
 * Extracts clean multi-paragraph extended overview and bullet points from raw description text,
 * removing Primary Sources blocks, Markdown tables, raw URLs, and AI disclaimers.
 */
export function buildCleanExtendedNotes(rawDescription: string): string {
  if (!rawDescription) return "";

  let cleaned = stripAiDisclaimers(rawDescription.replace(/\r\n/g, "\n"));

  // Cut off at "Primary Sources Referenced", "Source Classification Table", "The following table details the sources", "Link to Sources", or "### Keywords"
  cleaned = cleaned.replace(
    /(?:\n|^)\s*(?:#{1,6}\s*)?Primary Sources Referenced\b[\s\S]*$/i,
    ""
  );
  cleaned = cleaned.replace(
    /(?:\n|^)\s*The following table details the sources provided[\s\S]*$/i,
    ""
  );
  cleaned = cleaned.replace(
    /(?:\n|^)\s*(?:#{1,6}\s*)?Source Classification Table\b[\s\S]*$/i,
    ""
  );
  cleaned = cleaned.replace(
    /(?:\n|^)\s*Link to Sources\b[\s\S]*$/i,
    ""
  );
  cleaned = cleaned.replace(
    /(?:\n|^)\s*Sources\s*:\s*https?:\/\/[\s\S]*$/i,
    ""
  );
  cleaned = cleaned.replace(
    /(?:\n|^)\s*(?:#{1,6}\s*)?Keywords\b[\s\S]*$/i,
    ""
  );
  // Also strip inline "Primary Sources Referenced: ..." at the end of a paragraph
  cleaned = cleaned.replace(/\s*Primary Sources Referenced\s*:[\s\S]*$/i, "");

  const rawLines = cleaned.split("\n");
  const outputLines: string[] = [];

  for (const rawLine of rawLines) {
    const trimmed = rawLine.trim();
    if (!trimmed) {
      if (outputLines.length > 0 && outputLines[outputLines.length - 1] !== "") {
        outputLines.push("");
      }
      continue;
    }

    // Skip horizontal rules and markdown table rows
    if (/^-{3,}$/.test(trimmed) || (trimmed.startsWith("|") && trimmed.endsWith("|"))) {
      continue;
    }

    // Skip top-level episode title headers (# The CAB Call #17: ... or ## Episode Description: ...)
    if (
      /^#\s+The CAB Call\b/i.test(trimmed) ||
      /^Title:\s+/i.test(trimmed) ||
      /^#{1,6}\s*Episode Description\b/i.test(trimmed)
    ) {
      continue;
    }

    // Normalize section subheaders like "### What We Unpack in This Episode:" or "What You Will Learn:"
    if (/^(?:#{2,6}\s*)?(?:What You Will Learn|What We Unpack in This Episode|Key Takeaways|In this episode,\s*we cover)\s*:?$/i.test(trimmed)) {
      outputLines.push("Key Takeaways:");
      continue;
    }

    // Normalize bullet points (* **Topic:** ... or - Topic: ... or 1. **Topic:** ...)
    const bulletMatch = trimmed.match(/^(?:[*-]|\d+\.)\s+(.+)$/);
    if (bulletMatch) {
      const itemText = cleanMarkdownInline(bulletMatch[1]);
      if (itemText) {
        outputLines.push(`• ${itemText}`);
      }
      continue;
    }

    const lineText = cleanMarkdownInline(trimmed.replace(/^#{1,6}\s+/, ""));
    if (lineText) {
      outputLines.push(lineText);
    }
  }

  return outputLines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

/**
 * Extracts a crisp, self-contained 2–3 sentence hook for the episode card summary.
 * Guarantees zero Markdown link syntax, zero Markdown tables, zero raw URLs, and zero AI disclaimers.
 */
export function buildCleanEpisodeHook(rawDescription: string): string {
  const extended = buildCleanExtendedNotes(rawDescription);
  if (!extended) return "";

  // Take only prose paragraphs before "Key Takeaways:" or bullet points
  const beforeTakeaways = extended.split(/\n(?:Key Takeaways:|•\s)/i)[0].trim();
  const paragraphs = beforeTakeaways
    .split(/\n{2,}/)
    .map((p) => p.replace(/\n+/g, " ").trim())
    .filter(Boolean);

  if (paragraphs.length === 0) return "";

  // Drop generic 1-sentence welcome boilerplate if there are more substantive paragraphs following
  const filteredParagraphs =
    paragraphs.length > 1 &&
    /^Welcome back to The CAB Call[,.\s]/i.test(paragraphs[0]) &&
    paragraphs[0].length < 140
      ? paragraphs.slice(1)
      : paragraphs;

  const combinedProse = filteredParagraphs.join(" ");

  // Split into sentences while respecting common abbreviations
  const sentenceMatches =
    combinedProse.match(/[^.!?]+[.!?]+(?:\s|$)|[^.!?]+$/g)?.map((s) => s.trim()).filter(Boolean) ?? [
      combinedProse,
    ];

  const selectedSentences: string[] = [];
  let charCount = 0;

  for (const sentence of sentenceMatches) {
    // Skip generic welcome opener sentence if it's at the start of a multi-sentence paragraph
    if (
      selectedSentences.length === 0 &&
      sentenceMatches.length > 2 &&
      /^Welcome back to The CAB Call[,.\s]/i.test(sentence) &&
      sentence.length < 140
    ) {
      continue;
    }

    selectedSentences.push(sentence);
    charCount += sentence.length;

    if (selectedSentences.length >= 3 || (selectedSentences.length >= 2 && charCount >= 220)) {
      break;
    }
  }

  const hook = (selectedSentences.length > 0 ? selectedSentences.join(" ") : combinedProse).trim();
  return cleanMarkdownInline(stripAiDisclaimers(hook));
}

/**
 * Defensive read-time sanitizer for `episodes.summary` in D1 bridge / DTO mappers.
 */
export function sanitizeEpisodeSummaryDefensive(rawSummary: string): string {
  if (!rawSummary) return "";
  const needsSanitization =
    rawSummary.length > 480 ||
    /\[[^\]]+\]\(https?:\/\//.test(rawSummary) ||
    /\([^)]+\)\[https?:\/\//.test(rawSummary) ||
    /\[[^\]]+\]\[https?:\/\//.test(rawSummary) ||
    /https?:\/\/\S+/.test(rawSummary) ||
    /Primary Sources Referenced/i.test(rawSummary) ||
    /Source Classification Table/i.test(rawSummary) ||
    /What You Will Learn/i.test(rawSummary) ||
    /Disclaimer:\s*The media and artwork/i.test(rawSummary) ||
    /\|\s*:?-{2,}:?\s*\|/.test(rawSummary);

  if (!needsSanitization) {
    return cleanMarkdownInline(stripAiDisclaimers(rawSummary));
  }
  return buildCleanEpisodeHook(rawSummary);
}

